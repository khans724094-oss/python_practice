text = "Shahid Khan Shahid"

# 1. find
print("find:", text.find("Khan"))

# 2. rfind
print("rfind:", text.rfind("Shahid"))

# 3. rindex
print("rindex:", text.rindex("Shahid"))

# 4. startswith
print("startswith:", text.startswith("Shahid"))

# 5. endswith
print("endswith:", text.endswith("Shahid"))

# 6. count
print("count:", text.count("Shahid"))

# 7. replace
print("replace:", text.replace("Shahid", "King"))

# 8. capitalize
name = "sHAHID kHAN"
print("capitalize:", name.capitalize())